"""Anycubic Slicer-Next dialect: raw gcode -> .gcode.3mf package the Kobra firmware accepts.

Structure reverse-engineered from A-to-PC/Kobra-Slicer (bbs_3mf.cpp + GCode.cpp),
byte-verified by its author against real Slicer Next captures. The Kobra 3 family
firmware rejects plain .gcode and generic 3mf packages with error 10115 ("device
cannot parse the file") unless the package carries:
- plate_1.gcode with HEADER_BLOCK / EXECUTABLE_BLOCK_START / EXECUTABLE_BLOCK_HEAD /
  M75 / CONFIG_BLOCK markers in the real order
- plate_1.gcode.metadata (header + config block: the firmware's lightweight
  print-info copy, read without loading the full toolpath)
- plate_1.gcode.md5 (UPPERCASE md5 of the plate gcode text)
- slice_info.config with X-ACNext-Client-Type/-Version header items
- a producer line starting with the literal "; generated by AnycubicSlicer"
  (firmware upload handler checks the prefix; confirmed from the binary)
"""
import hashlib
import json
import re
import zipfile
from datetime import datetime
from pathlib import Path

SLICER_VERSION = "2.4.2"
FLUSH_MATRIX = [0, 140, 140, 140, 140, 0, 140, 140, 140, 140, 0, 140, 140, 140, 140, 0]
FLUSH_VECTOR = [140, 0, 0, 0, 0, 140, 0, 0, 0, 0, 140, 0, 0, 0, 0, 140]


def _parse_prusa_tail(lines):
    """Split PrusaSlicer gcode into (body_lines, tail_config_dict, tail_cfg_lines)."""
    cfg_begin = next(i for i, l in enumerate(lines) if "prusaslicer_config = begin" in l)
    cfg_end = next(i for i, l in enumerate(lines) if "prusaslicer_config = end" in l)
    cfg_lines = [l[2:] if l.startswith("; ") else l.lstrip("; ")
                 for l in lines[cfg_begin + 1:cfg_end]]
    cfg = {}
    for l in cfg_lines:
        if " = " in l:
            k, v = l.split(" = ", 1)
            cfg[k.strip()] = v.strip()
    body = lines[:cfg_begin]
    first_code = next((i for i, l in enumerate(body) if l and not l.startswith(";")), 0)
    if first_code > 0:
        body = body[first_code - 1:]  # keep one blank line of separation
    return body, cfg, cfg_lines


def _with_anycubic_markers(body):
    """Insert EXECUTABLE_BLOCK_HEAD + T0 + M75 around the first tool select."""
    out = []
    for l in body:
        out.append(l)
        if re.match(r"^T0\b", l.strip()):
            out.append("M75 ; The first extruder is ready.")
            out.insert(-2, "; EXECUTABLE_BLOCK_HEAD")
            return out
    for i, l in enumerate(out):
        if l.startswith("G1"):
            out[i:i] = ["; EXECUTABLE_BLOCK_HEAD", "T0", "M75 ; The first extruder is ready."]
            break
    return out


def build_package(gcode_path: str, profiles_dir: str, out_path: str,
                  model_name: str = "print") -> str:
    """Transform a raw PrusaSlicer .gcode into an Anycubic .gcode.3mf package.
    Returns the package path. Strips the firmware-crashing filament_colour_type line."""
    raw = Path(gcode_path).read_text(errors="replace")
    raw = "\n".join(l for l in raw.splitlines()
                    if not (l.strip().startswith(";") and "filament_colour_type" in l))
    lines = raw.splitlines()
    body, cfg, cfg_lines = _parse_prusa_tail(lines)
    body = _with_anycubic_markers(body)

    total_layers = sum(1 for l in body if l.startswith("G1") and " Z" in l)
    fil_d = cfg.get("filament_diameter", "1.75").strip("[]")
    fil_den = cfg.get("filament_density", "1.24").strip("[]")
    max_z = cfg.get("max_print_height", "260")
    bed_t = cfg.get("first_layer_bed_temperature", "60").strip("[]").split(",")[0]

    header = [
        "; HEADER_BLOCK_START",
        f"; generated by AnycubicSlicer (AnycubicSlicerNext {SLICER_VERSION}) on "
        + datetime.now().strftime("%Y-%m-%d at %H:%M:%S UTC"),
        f"; total layer number: {total_layers}",
        f"; filament_density: [{fil_den}]",
        f"; filament_diameter: [{fil_d}]",
        f"; max_z_height: {max_z}",
        # 1-based extruder ids: used_filaments[idx] + 1 in the reference writer
        "; filament: [1]",
        "; exclude_object: 1",
        "; model_instances: 1",
        "; source_info: {\"models\":[{\"file_source\":0,\"mo_file_id\":-1,\"name\":\""
        + model_name + "\",\"referrer_source\":-1}],\"models_from\":0,\"plate_index\":1,"
        "\"slice_paras_process\":1,\"software_version\":\"AnycubicSlicerNext "
        + SLICER_VERSION + "\"}",
        "; paint_info = [{\"material_type\":\"PLA\",\"paint_color\":[255,255,255],"
        "\"paint_index\":0}]",
        "; project_info = {\"flush_multiplier\":1.0,"
        "\"flush_volumes_chan_multipliers\":[1,1],"
        "\"flush_volumes_matrix\":[" + ",".join(map(str, FLUSH_MATRIX)) + "],"
        "\"flush_volumes_vector\":[" + ",".join(map(str, FLUSH_VECTOR)) + "]}",
        "; flush_multiplier_calculate_by_acnext: 1",
        "; test_mode: 0",
        "; HEADER_BLOCK_END",
        "",
        "; EXECUTABLE_BLOCK_START",
    ]
    paint = ('; paint_info = [{"material_type":"PLA","paint_color":[255,255,255],'
             '"paint_index":0}]')
    tail = (
        ["; CONFIG_BLOCK_START = begin",
         "; AnycubicSlicer_config = begin",
         f"; bed_temperature = {bed_t}"]
        + cfg_lines +
        ["; AnycubicSlicer_config = end",
         "; CONFIG_BLOCK_END = end",
         "",
         "; ams_info = begin",
         paint,
         "; ams_info = end",
         ""])
    plate_gcode = "\n".join(header + body + tail) + "\n"

    exec_pos = plate_gcode.find("; EXECUTABLE_BLOCK_START")
    cfg_pos = plate_gcode.find("; CONFIG_BLOCK_START")
    if exec_pos < 0 or cfg_pos < 0 or cfg_pos < exec_pos:
        raise RuntimeError("dialect markers missing after transform")
    plate_metadata = plate_gcode[:exec_pos] + plate_gcode[cfg_pos:]
    plate_md5 = hashlib.md5(plate_gcode.encode()).hexdigest().upper()

    slice_info = (
        '<?xml version="1.0" encoding="UTF-8"?>\n<config>\n'
        "  <header>\n"
        "    <header_item key=\"X-ACNext-Client-Type\" value=\"slicer\"/>\n"
        f"    <header_item key=\"X-ACNext-Client-Version\" value=\"{SLICER_VERSION}\"/>\n"
        "  </header>\n"
        "  <plate>\n"
        "    <metadata key=\"index\" value=\"1\"/>\n"
        "    <metadata key=\"printer_model_id\" value=\"K3 V2\"/>\n"
        "    <metadata key=\"nozzle_diameters\" value=\"0.4\"/>\n"
        "    <metadata key=\"timelapse_type\" value=\"0\"/>\n"
        "    <metadata key=\"prediction\" value=\"0\"/>\n"
        "    <metadata key=\"weight\" value=\"0\"/>\n"
        "    <metadata key=\"outside\" value=\"false\"/>\n"
        "    <metadata key=\"support_used\" value=\"false\"/>\n"
        "    <metadata key=\"label_object_enabled\" value=\"true\"/>\n"
        "    <filament id=\"1\" tray_info_idx=\"GFPLA\" type=\"PLA\"/>\n"
        "  </plate>\n"
        "</config>\n"
    )
    model_settings = (
        '<?xml version="1.0" encoding="UTF-8"?>\n<config>\n'
        "  <plate>\n"
        "    <metadata key=\"plater_id\" value=\"1\"/>\n"
        "    <metadata key=\"plater_name\" value=\"\"/>\n"
        "    <metadata key=\"gcode_file\" value=\"Metadata/plate_1.gcode\"/>\n"
        "    <metadata key=\"gcode_file_md5\" value=\"" + plate_md5 + "\"/>\n"
        "  </plate>\n"
        "</config>\n"
    )

    proj = {}
    for name in ("Anycubic Kobra 3 V2 0.4 nozzle.json",
                 "Anycubic PLA @Anycubic Kobra 3 V2 0.4 nozzle.json",
                 "0.20mm Standard @Anycubic Kobra 3 V2 0.4 nozzle.json"):
        p = Path(profiles_dir) / name
        if p.exists():
            proj.update(json.loads(p.read_text()))

    out = Path(out_path)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml",
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>'
            '<Default Extension="gcode" ContentType="text/plain"/>'
            '<Default Extension="md5" ContentType="text/plain"/>'
            '<Default Extension="metadata" ContentType="application/octet-stream"/>'
            '<Default Extension="config" ContentType="application/octet-stream"/>'
            '<Default Extension="json" ContentType="application/json"/>'
            '<Default Extension="png" ContentType="image/png"/></Types>')
        z.writestr("_rels/.rels",
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Target="/3D/3dmodel.model" Id="rel-1" '
            'Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
        z.writestr("3D/3dmodel.model",
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<model unit="millimeter" xml:lang="en-US" '
            'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">'
            '<resources><object id="1" type="model"><mesh>'
            '<vertices><vertex x="0" y="0" z="0"/><vertex x="10" y="0" z="0"/>'
            '<vertex x="0" y="10" z="0"/></vertices>'
            '<triangles><triangle v1="0" v2="1" v3="2"/></triangles>'
            '</mesh></object></resources><build><item objectid="1"/></build></model>')
        z.writestr("Metadata/plate_1.gcode", plate_gcode)
        z.writestr("Metadata/plate_1.gcode.metadata", plate_metadata)
        z.writestr("Metadata/plate_1.gcode.md5", plate_md5)
        z.writestr("Metadata/slice_info.config", slice_info)
        z.writestr("Metadata/model_settings.config", model_settings)
        if proj:
            z.writestr("Metadata/project_settings.config", json.dumps(proj))
    return str(out)
